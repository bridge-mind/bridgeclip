const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { buildApp, launchApp } = require('../zernio/support/electron-app.cjs')

test('Advanced models and export speed support keyboard selection, review and submission in Electron', { timeout: 90000 }, async (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bridgeclip-models-e2e-'))
  const appDir = buildApp(path.join(root, 'app'))
  const session = await launchApp({ appDir, userDataDir: path.join(root, 'user-data') })
  t.after(async () => { await session.close(); fs.rmSync(root, { recursive: true, force: true }) })
  const { app, page } = session
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  // Keep the real models:list IPC and parser; replace only the public HTTP catalog.
  // No keys, audio, video or paid inference requests are used in this test.
  await app.evaluate(({ ipcMain, BrowserWindow }, root) => {
    BrowserWindow.getAllWindows()[0].setSize(1300, 1100)
    globalThis.modelTest = { fail: true, calls: [], submitted: null }
    globalThis.fetch = async (url, options) => {
      globalThis.modelTest.calls.push({ url, headers: options.headers })
      if (globalThis.modelTest.fail) throw new Error('Offline catalog')
      if (!url.startsWith('https://openrouter.ai/api/v1/models?')) throw new Error('Unexpected network request')
      const stt = url.endsWith('transcription')
      return Response.json({ data: stt ? [
        { id: 'openai/whisper-large-v3', name: 'OpenAI: Whisper Large V3', architecture: { input_modalities: ['audio'], output_modalities: ['transcription'] } },
        { id: 'openai/gpt-4o-transcribe', name: 'OpenAI: GPT-4o Transcribe', architecture: { input_modalities: ['audio'], output_modalities: ['transcription'] } }
      ] : [
        { id: 'google/gemini-3.8-flash', name: 'Google: Gemini 3.8 Flash', architecture: { input_modalities: ['text', 'image'], output_modalities: ['text'] },
          supported_parameters: ['structured_outputs'], context_length: 1048576, top_provider: { max_completion_tokens: 65536 }, pricing: { prompt: '0.00000075', completion: '0.00000375' } }
      ] })
    }
    ipcMain.removeHandler('settings:load')
    ipcMain.handle('settings:load', () => ({ openrouterConfigured: true, zernioConfigured: false, outputDirectory: root, pythonPath: '', customVocabulary: '' }))
    ipcMain.removeHandler('system:checkTools')
    ipcMain.handle('system:checkTools', () => ({ python: true, pythonDeps: true, ffmpeg: true, ffmpegCaptions: true, ffprobe: true, ytdlp: true, engine: true, bridgeRunner: true }))
    ipcMain.removeHandler('job:start')
    ipcMain.handle('job:start', (_event, config) => { globalThis.modelTest.submitted = config; return { jobId: 'test-advanced', queued: false } })
    ipcMain.removeHandler('source:youtubePreview')
    ipcMain.handle('source:youtubePreview', () => ({ title: 'The art of a great conversation', channel: 'BridgeClip Studio', durationSeconds: 900, viewCount: 12500, uploadedOn: '2026-09-20' }))
  }, root)
  await page.route('https://i.ytimg.com/**', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="640" height="360"><rect width="640" height="360" fill="#202530"/><circle cx="320" cy="150" r="65" fill="#4e6282"/><text x="100" y="300" fill="white" font-family="sans-serif" font-size="24">A GREAT CONVERSATION</text></svg>' }))
  await page.reload()
  await page.getByPlaceholder('YouTube, Twitch VOD or direct video link').fill('https://youtu.be/aqz-KE-bpKQ')
  await page.getByRole('button', { name: 'Use link', exact: true }).click()
  await page.getByRole('radio', { name: 'Automatic', exact: true }).click()
  const steps = page.getByRole('navigation', { name: 'Create steps' })
  await steps.getByRole('button', { name: /Format/ }).click()
  const speeds = page.getByRole('radiogroup', { name: 'Video speed' })
  await speeds.getByRole('radio', { name: '1× (Normal)', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  assert.equal(await speeds.getByRole('radio', { name: '1.5×', exact: true }).getAttribute('aria-checked'), 'true')
  const artifacts = process.env.BRIDGECLIP_E2E_SHOTS
  if (artifacts) {
    fs.mkdirSync(artifacts, { recursive: true })
    await page.screenshot({ path: path.join(artifacts, 'advanced-video-speed.png') })
  }
  await steps.getByRole('button', { name: /Clips/ }).click()
  await page.getByText(/60 seconds becomes about 40 seconds/).waitFor()
  await page.getByRole('radio', { name: /Advanced/ }).click()
  await page.getByRole('alert').filter({ hasText: 'Could not load OpenRouter models' }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Generate now', exact: true }).isDisabled(), true)
  await app.evaluate(() => { globalThis.modelTest.fail = false })
  await page.getByRole('button', { name: 'Refresh models' }).click()
  const speech = page.getByRole('combobox', { name: 'Transcription model', exact: true })
  await speech.fill('does not exist')
  await page.getByText('No matching models.', { exact: false }).waitFor()
  await speech.fill('gpt-4o')
  assert.equal(await page.getByRole('option').getAttribute('aria-disabled'), 'true')
  await speech.fill('whisper large')
  await speech.press('ArrowDown')
  await speech.press('Enter')
  assert.equal(await speech.inputValue(), 'OpenAI: Whisper Large V3')
  const planner = page.getByRole('combobox', { name: 'Clip planning model', exact: true })
  await planner.fill('gemini')
  await page.getByRole('option', { name: /Google: Gemini/ }).click()
  assert.equal(await app.evaluate(() => globalThis.modelTest.submitted), null, 'Enter must select a model, not submit a job')
  await page.getByRole('radio', { name: /Economy/ }).click()
  assert.equal(await page.getByRole('combobox').count(), 0)
  await page.getByRole('radio', { name: /Advanced/ }).click()
  assert.equal(await speech.inputValue(), 'OpenAI: Whisper Large V3')
  assert.equal(await planner.inputValue(), 'Google: Gemini 3.8 Flash')
  await app.evaluate(() => { globalThis.modelTest.fail = true })
  await page.getByRole('button', { name: 'Refresh models' }).click()
  await page.getByRole('alert').filter({ hasText: 'Could not load OpenRouter models' }).waitFor()
  assert.equal(await planner.inputValue(), 'Google: Gemini 3.8 Flash')
  await app.evaluate(() => { globalThis.modelTest.fail = false })
  await page.getByRole('button', { name: 'Refresh models' }).click()
  await page.getByRole('alert').filter({ hasText: 'Could not load OpenRouter models' }).waitFor({ state: 'hidden' })
  if (artifacts) await page.screenshot({ path: path.join(artifacts, 'advanced-mode.png') })
  await steps.getByRole('button', { name: /Review/ }).click()
  await page.getByRole('region', { name: 'Format & pace', exact: true }).getByText('1.5× speed', { exact: true }).waitFor()
  const modeSummary = page.getByRole('region', { name: 'Clipping mode', exact: true })
  await modeSummary.getByText('Advanced', { exact: true }).waitFor()
  await modeSummary.getByText('Google: Gemini 3.8 Flash', { exact: true }).waitFor()
  await modeSummary.getByText('OpenAI: Whisper Large V3', { exact: true }).waitFor()
  const sourceSummary = page.getByRole('region', { name: 'Video summary', exact: true })
  await sourceSummary.getByRole('heading', { name: 'The art of a great conversation', exact: true }).waitFor()
  await sourceSummary.getByText('BridgeClip Studio', { exact: true }).waitFor()
  await sourceSummary.getByText('15:00', { exact: true }).waitFor()
  await sourceSummary.getByRole('img', { name: 'Video thumbnail', exact: true }).waitFor()
  assert.equal(await sourceSummary.getByRole('button', { name: 'Remove video', exact: true }).count(), 0)
  if (artifacts) await page.screenshot({ path: path.join(artifacts, 'wizard-review.png'), animations: 'disabled' })
  await page.getByRole('button', { name: 'Edit format', exact: true }).click()
  await page.getByRole('radiogroup', { name: 'Format', exact: true }).getByRole('radio', { name: /Horizontal/ }).click()
  await steps.getByRole('button', { name: /Review/ }).click()
  await page.getByRole('region', { name: 'Format & pace', exact: true }).getByText('Whole frame', { exact: true }).waitFor()
  assert.equal(await page.getByText('AI vision', { exact: true }).count(), 0)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(720, 700))
  await page.waitForFunction(() => window.innerWidth === 720 && document.documentElement.scrollWidth <= window.innerWidth)
  if (artifacts) await page.screenshot({ path: path.join(artifacts, 'wizard-review-compact.png'), animations: 'disabled' })
  await page.getByRole('button', { name: 'Generate clips', exact: true }).click()
  await page.getByRole('button', { name: 'View job' }).waitFor()
  const result = await app.evaluate(() => globalThis.modelTest)
  assert.equal(result.submitted.clippingMode, 'advanced')
  assert.equal(result.submitted.plannerModel, 'google/gemini-3.8-flash')
  assert.equal(result.submitted.transcriptionModel, 'openai/whisper-large-v3')
  assert.equal(result.submitted.videoSpeed, 1.5)
  assert.equal(result.submitted.videoUrl, 'https://youtu.be/aqz-KE-bpKQ')
  assert.equal(result.submitted.aspectRatio, '16:9')
  assert.equal(result.submitted.layoutVision, false)
  await page.getByRole('button', { name: 'Clip another video' }).click()
  await page.getByPlaceholder('YouTube, Twitch VOD or direct video link').fill('https://example.com/next.mp4')
  await page.getByRole('button', { name: 'Use link', exact: true }).click()
  await page.getByRole('radio', { name: 'Automatic', exact: true }).click()
  await steps.getByRole('button', { name: /Format/ }).click()
  assert.equal(await speeds.getByRole('radio', { name: '1.5×', exact: true }).getAttribute('aria-checked'), 'true')
  assert.ok(result.calls.every(({ headers }) => !Object.keys(headers).some((name) => name.toLowerCase() === 'authorization')))
  assert.deepEqual(errors, [])
})
